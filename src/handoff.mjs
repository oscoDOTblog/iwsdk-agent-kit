import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';

const LIMIT = 16000;
function textFile(path) {
  return existsSync(path) ? readFileSync(path, 'utf8') : '';
}
function gitInfo(worktree, ...args) {
  if (!existsSync(worktree)) return '(worktree not created)';
  const result = spawnSync('git', args, { cwd: worktree, encoding: 'utf8' });
  return result.status === 0 ? (result.stdout.trim() || '(clean)') : '(git inspection unavailable)';
}
export function handoffPath(state, feature) {
  return join(state.directory, 'handoffs', feature.id + '.md');
}
export function sharedContext(state) {
  const path = join(state.repo, 'AGENT_CONTEXT.md');
  const content = textFile(path);
  if (!content) return '(AGENT_CONTEXT.md is not installed or is empty)';
  if (content.length <= LIMIT) return content;
  return content.slice(0, LIMIT) + '\n[Context truncated; read AGENT_CONTEXT.md directly for the rest.]';
}
export function handoffContext(state, feature) {
  const path = handoffPath(state, feature);
  const content = textFile(path);
  return content.length <= LIMIT ? content : content.slice(0, LIMIT) + '\n[Handoff truncated; read the file directly.]';
}
export function renderHandoff(state, feature, details = {}) {
  const checklist = feature.acceptance ?? [];
  const summary = details.summary?.trim() || '(No agent summary recorded; inspect attempt logs and Git state.)';
  return [
    '# Agent handoff: ' + state.id + ' / ' + feature.id,
    '',
    'Generated by the IWSDK Agent Kit coordinator. This file is local to Git metadata, not a Git commit.',
    'Treat agent reports as unverified until independently checked.',
    '',
    '## Assignment',
    '- Task: ' + feature.description,
    '- Status: ' + feature.status,
    '- Backend: ' + (feature.backend ?? state.backend),
    '- Branch: ' + feature.branch,
    '- Baseline commit: ' + state.baseline,
    '- Worktree: ' + feature.worktree,
    '- Current commit: ' + (details.head ?? '(unknown)'),
    '- Last error: ' + (feature.error ?? '(none)'),
    '',
    '## Acceptance criteria',
    ...checklist.map(value => '- ' + value),
    '',
    '## Owned paths',
    ...(feature.owns ?? []).map(value => '- ' + value),
    '',
    '## Git status (inspect before continuing)',
    '```',
    details.status || '(clean or worktree not created)',
    '```',
    '',
    '## Last agent report (unverified)',
    summary.slice(0, LIMIT),
    '',
    '## Next agent instructions',
    '1. Read AGENTS.md, AGENT_CONTEXT.md and this handoff.',
    '2. Inspect the feature branch, Git status and the previous attempt logs before writing.',
    '3. Preserve all partial work. Never reset, stash, or overwrite without review.',
    '4. Work only in owned paths and re-run available project checks.',
    '5. Commit finished changes, then report what was verified and what remains.',
    '',
  ].join('\n');
}
export function writeHandoff(state, feature) {
  const summaryPath = feature.attemptDirectory && join(feature.attemptDirectory, 'summary.md');
  const summary = summaryPath && existsSync(summaryPath) ? textFile(summaryPath) : '';
  const details = {
    summary,
    status: gitInfo(feature.worktree, 'status', '--short', '--untracked-files=all'),
    head: gitInfo(feature.worktree, 'rev-parse', 'HEAD'),
  };
  const path = handoffPath(state, feature);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, renderHandoff(state, feature, details));
  return path;
}

/** Advisory only: never trigger an automatic backend switch from log text. */
export function classifyFailure(raw) {
  if (/\b(?:rate[- ]limit(?:ed|ing)?|quota exceeded|usage limit|usage cap|insufficient credits|too many requests|weekly limit reached|monthly limit reached|subscription limit reached)\b/i.test(raw)) return 'possible-usage-limit';
  if (/\b(?:permission denied|approval denied|unauthorized|authentication failed)\b/i.test(raw)) return 'permission-or-auth';
  return 'unclassified';
}
